/**
 * @file
 *
 * How many terminal cells a character occupies, and where that puts the one
 * after it.
 *
 * **This is not Unicode data.** It is vim 9.1's, measured with
 * `strdisplaywidth()` over all 1,114,112 code points - a table of its own
 * that resembles East_Asian_Width and is not it. The library needs it for
 * exactly one construct, `\%23v`, which asks whether the *screen* column
 * here is 23; the shared assertion that answers it is
 * GRX_ASSERT_SCREEN_COLUMN, and no engine knows which dialect wrote it.
 *
 * Four kinds of entry, and the fourth is the reason this is a function and
 * not a lookup:
 *
 * - **One cell** is the default, so the table below holds only the
 *   exceptions - 506 ranges out of 1,114,112 code points.
 * - **Two** for a wide or fullwidth character, and for a C0 control, which
 *   vim draws as `^X`.
 * - **Zero** for a combining character that follows something. 2,033 code
 *   points, a strict subset of `Mn | Me | Cf` - 209 of that property's
 *   members are one cell in vim - which is why the set is written out
 *   rather than named. A zero-width character with nothing before it is
 *   drawn on its own and takes one cell, which is
 *   grx_display_cell_width()'s `first` parameter.
 * - **Four, six or seven** for the `<xx>` and `<uxxxx>` forms vim uses for
 *   an unprintable code point.
 *
 * The tab is none of these: it advances to the next multiple of the
 * tabstop, so its width depends on where it starts.
 * grx_display_column_after() is what knows that, and it is the only caller
 * that needs to.
 */

