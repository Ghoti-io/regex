uint32_t grx_display_cell_width(uint32_t codepoint, int first) {
  size_t low = 0;
  size_t high = sizeof(cell_widths) / sizeof(*cell_widths);
  while (low < high) {
    size_t mid = low + (high - low) / 2;
    if (codepoint < cell_widths[mid].lo) {
      high = mid;
    }
    else if (codepoint > cell_widths[mid].hi) {
      low = mid + 1;
    }
    else {
      uint32_t cells = cell_widths[mid].cells;
      // A combining character with nothing to combine with is drawn on its
      // own: `\%2v` holds one character into a subject that begins with
      // U+0301 and two characters into one that begins with "a".
      return (!cells && first) ? 1u : cells;
    }
  }
  return 1;
}

size_t grx_display_column_after(
    uint32_t codepoint, size_t column, size_t tabstop, int first) {
  if (codepoint == 0x09 && tabstop) {
    // To the next multiple of the tabstop, counting columns from one:
    // a tab at column 1 ends at column 9 with the default eight.
    return column + (tabstop - ((column - 1) % tabstop));
  }
  return column + grx_display_cell_width(codepoint, first);
}
