uint32_t grx_vim_char_class(uint32_t codepoint) {
  size_t low = 0;
  size_t high = sizeof(vim_classes) / sizeof(*vim_classes);
  while (low < high) {
    size_t mid = low + (high - low) / 2;
    if (codepoint < vim_classes[mid].lo) {
      high = mid;
    }
    else if (codepoint > vim_classes[mid].hi) {
      low = mid + 1;
    }
    else {
      return vim_classes[mid].cls;
    }
  }
  return GRX_VIM_CLASS_KEYWORD;
}

/**
 * The class of the character on one side of a position, or class 0 where
 * there is no character there.
 *
 * Vim reads a NUL past the end of the line and calls it class 0, and refuses
 * `\>` at the start of one before it looks at all; both of those are what
 * "nothing there is a blank" comes to, and saying it once here is what keeps
 * the two rules below the two lines they are.
 */
static uint32_t side(int has, uint32_t codepoint) {
  return has ? grx_vim_char_class(codepoint) : GRX_VIM_CLASS_BLANK;
}

int grx_vim_word_start(
    int has_before, uint32_t before, int has_after, uint32_t after) {
  uint32_t left = side(has_before, before);
  uint32_t right = side(has_after, after);
  return right >= GRX_VIM_CLASS_KEYWORD && right != left;
}

int grx_vim_word_end(
    int has_before, uint32_t before, int has_after, uint32_t after) {
  uint32_t left = side(has_before, before);
  uint32_t right = side(has_after, after);
  return left >= GRX_VIM_CLASS_KEYWORD && right != left;
}
