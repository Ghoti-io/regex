#!/usr/bin/env python3
"""Regenerate bounded, offline Java syntax and match vectors from JDK 25.

The selected rows have scalar UTF-8 inputs and use only the first-match or
compile modes that the .rxt runner can represent. The oracle answers, never
the C implementation, decide expectations. JDK 27 is a forward comparison
and must never be used to write this corpus.
"""

import argparse
import os

import java_probe
import make_vectors
import oracle_env

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PIN = "java25"
AREAS = {"shared", "control", "classes", "captures", "escapes",
         "refusal", "flags", "lines", "unicode", "unicode-sensitive",
         # The escape alphabet and what the letters in it mean. Both are
         # here for the reason the file exists: a fresh clone with no
         # container runs the `.rxt` corpus and nothing else, so an escape
         # whose only gate is the differential is ungated for that reader.
         # The semantics half is the one that found a defect - the JDK's
         # `\R` splits a CR LF pair and perl's does not - and a compile-only
         # corpus could not have carried it.
         "escape-alphabet", "escape-semantics"}


def selected():
    """Keep source case IDs stable and bound the committed corpus."""
    return [(i, row) for i, row in enumerate(java_probe.CASES)
            if row["mode"] in ("first", "compile") and row["area"] in AREAS
            and not any(flag in row["flags"] for flag in "lc")]


def record(row, answer):
    lines = ["pattern: " + make_vectors.escape(row["pattern"])]
    if row["flags"]:
        lines.append("flags: " + row["flags"])
    kind = answer["kind"]
    if kind == "syntax":
        lines.append("expect: refused")
    elif row["mode"] == "compile":
        if kind != "compile":
            raise ValueError(f"compile row received {answer}")
        lines.append("expect: compiles")
    elif kind in ("match", "nomatch"):
        lines.append("subject: " + make_vectors.escape(row["subject"]))
        if kind == "nomatch":
            lines.append("expect: nomatch")
        else:
            spans = ["-" if span is None else f"{span[0]}-{span[1]}"
                     for span in answer["groups"]]
            lines.append("expect: " + " ".join(spans))
    else:
        raise ValueError(f"unrepresentable oracle answer: {answer}")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=os.path.join(
        ROOT, "tests", "data", "vectors", "java", "generated.rxt"))
    args = parser.parse_args()
    if oracle_env.MODE != "container" or os.environ.get("GHOTI_ORACLE_ALIAS", "").strip():
        raise SystemExit("Java vector recording requires the unaliased pinned container")
    rows = selected()
    answers = java_probe.run(PIN, [row for _, row in rows])
    digest, version, _ = oracle_env.pins()[PIN]
    oracle_env.check_pin(PIN)
    body = []
    refused = set()
    for (case_id, row), answer in zip(rows, answers):
        if answer["kind"] == "syntax":
            key = (row["flags"], row["pattern"])
            if key in refused:
                continue
            refused.add(key)
        body.append(f"# case: {case_id}\n" + record(row, answer))
    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as out:
        out.write("# generated by tools/oracle/make_java_vectors.py\n")
        out.write(f"# fixed inventory revision: {java_probe.GENERATED_INVENTORY_REVISION}; oracle: {digest}\n")
        out.write(f"# runtime: {version}\n")
        out.write("# JDK 25 expectations; JDK 27 is recorded separately.\n")
        out.write("dialect: java\n\n")
        out.write("\n\n".join(body) + "\n")
    print(f"{args.out}: {len(body)} records from {len(rows)} oracle rows")


if __name__ == "__main__":
    main()
